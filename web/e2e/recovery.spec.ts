import { expect, portalNumber, test, unavailableReply, visitAnswer, visitDate, visitQuestion, visitSource } from './fixtures'

test('普通挂号独立恢复医生列表与号源，保留原科室和日期时段', async ({ page, patientApi }) => {
  patientApi.failNext('GET /departments/2002/doctors')
  await page.goto('/booking?departmentId=2002')
  await expect(page.getByRole('alert').filter({ hasText: '医生列表加载失败' })).toBeVisible()
  const date = page.getByLabel('就诊日期')
  const afternoon = page.getByRole('button', { name: '下午', exact: true })
  await date.fill(visitDate)
  await afternoon.click()
  await expect(page.getByText('2 个号源', { exact: true })).toBeVisible()
  patientApi.failNext('GET /slots')
  await page.getByRole('button', { name: '重新查询', exact: true }).click()
  const errors = page.getByRole('alert')
  await expect(errors).toHaveCount(2)
  const previousSearches = patientApi.requestsFor('GET /slots').length

  await page.getByRole('button', { name: '重新加载医生' }).click()
  const doctor = page.getByRole('button', { name: /^周宁/ })
  await expect(doctor).toBeVisible()
  await expect(errors).toHaveCount(1)
  await expect(date).toHaveValue(visitDate)
  await expect(afternoon).toHaveAttribute('aria-pressed', 'true')
  expect(patientApi.requestsFor('GET /slots')).toHaveLength(previousSearches)
  await doctor.click()
  await expect(page.getByText('2 个号源', { exact: true })).toBeVisible()
  expect(patientApi.requestsFor('GET /slots').at(-1)?.query).toEqual({
    departmentId: '2002', doctorId: '3003', date: visitDate, period: 'AFTERNOON',
  })
})

test('导诊预约条件中的科室和医生加载失败可以原地重试', async ({ page, patientApi }) => {
  patientApi.failNext('GET /departments')
  await page.goto('/guide')
  await page.getByRole('button', { name: '填写预约条件' }).click()
  const form = page.locator('#guide-condition-editor')
  await expect(form.getByRole('alert')).toContainText('科室列表加载失败')
  await form.getByRole('button', { name: '重新加载科室' }).click()
  const department = form.getByLabel('科室', { exact: true })
  patientApi.failNext('GET /departments/2002/doctors')
  await department.selectOption({ label: '呼吸内科' })
  await expect(form.getByRole('alert')).toContainText('医生列表加载失败')

  await form.getByLabel('就诊日期').fill(visitDate)
  await form.getByLabel('就诊时段').selectOption('AFTERNOON')
  await form.getByRole('button', { name: '重新加载医生' }).click()
  await form.getByLabel('医生', { exact: true }).selectOption({ label: '周宁' })
  await expect(department).toHaveValue('2002')
  await expect(form.getByLabel('就诊日期')).toHaveValue(visitDate)
  await expect(form.getByLabel('就诊时段')).toHaveValue('AFTERNOON')
  await expect(form.getByRole('alert')).toHaveCount(0)
})

test('普通挂号丢失确认响应后，刷新并核验原单只创建一次', async ({ page, patientApi }) => {
  patientApi.loseNextBookingResponse()
  await page.goto('/booking?departmentId=2002')
  await page.getByRole('button', { name: '选此号源' }).first().click()
  await page.getByRole('button', { name: '确认预约', exact: true }).click()
  await expect(page.getByText('提交结果暂未确定，请先核验原预约。')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '核验原预约', exact: true }).click()
  await expect(page.getByText('该预约已存在', { exact: true })).toBeVisible()
  const creates = patientApi.requestsFor('POST /appointments')
  expect(creates).toHaveLength(1)
  expect(creates[0].body.idempotencyKey).toMatch(/^[0-9a-f-]{36}$/)
  expect(patientApi.requestsFor('POST /appointments/status').map(request => request.body)).toEqual([creates[0].body])
  expect(patientApi.appointments).toHaveLength(1)
})

test('就诊准备重试加载，连续查询失败显示一条，恢复后可以展开来源', async ({ page, patientApi }) => {
  patientApi.seedAppointment()
  patientApi.failNext('POST /appointments/' + portalNumber + '/consultation')
  patientApi.failVisitQueries(2)
  await page.goto('/appointments/' + portalNumber + '/preparation')
  await expect(page.getByRole('alert')).toContainText('这笔预约暂时无法打开咨询')
  await page.getByRole('button', { name: '重试加载' }).click()
  await page.getByRole('button', { name: visitQuestion }).click()
  await expect(page.getByRole('alert')).toContainText(unavailableReply)
  await page.reload()
  await expect(page.getByRole('alert')).toContainText(unavailableReply)
  const retry = page.getByRole('button', { name: '重试查询' })
  await retry.click()
  await expect(retry).toBeEnabled()
  await expect(page.getByText(unavailableReply, { exact: true })).toHaveCount(1)
  await expect(page.locator('.visit-question')).toHaveCount(1)
  await retry.click()
  await expect(page.getByText(visitAnswer, { exact: true })).toBeVisible()
  await expect(page.locator('.visit-question')).toHaveCount(1)
  await expect(page.getByText(unavailableReply, { exact: true })).toHaveCount(0)
  const region = page.getByRole('region', { name: '资料来源' })
  await region.getByText(/演示门诊须知.*报到凭证/).click()
  await expect(region.getByText(visitSource.content)).toBeVisible()
  const attempts = patientApi.requestsFor('POST /tasks/visit-' + portalNumber + '/messages/stream')
  expect(attempts).toHaveLength(3)
  expect(new Set(attempts.map(request => request.body.clientRequestId)).size).toBe(3)
})

test('就诊准备响应中断后，刷新重试沿用原问题和请求标识', async ({ page, patientApi }) => {
  patientApi.seedAppointment()
  const request = 'POST /tasks/visit-' + portalNumber + '/messages/stream'
  patientApi.interruptNext(request)
  await page.goto('/appointments/' + portalNumber + '/preparation')
  await page.getByRole('button', { name: visitQuestion }).click()
  await expect(page.getByRole('alert')).toContainText('结果尚未确认')
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('上次查询的结果尚未确认')
  await page.getByRole('button', { name: '重试查询' }).click()
  await expect(page.getByText(visitAnswer, { exact: true })).toBeVisible()
  const attempts = patientApi.requestsFor(request)
  expect(attempts).toHaveLength(2)
  expect(attempts[1].body).toEqual(attempts[0].body)
  await expect(page.locator('.visit-question')).toHaveCount(1)
})
